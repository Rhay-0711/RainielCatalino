    //valida si el campo tiene informacion
    private void validarCampo() {

        //evalua si el en el  campo hay texto o mejor dicho un numero
        if (practicas.getText().trim().length() <= 0) {
            JOptionPane.showMessageDialog(null, "Necesita ingresar un valor en PRACTICAS");
            practicas.requestFocus();
        } else if (parciales.getText().trim().length() <= 0) {
            JOptionPane.showMessageDialog(null, "Necesita ingresar un valor en PARCIALES");
            parciales.requestFocus();
        } else if (asignaciones.getText().trim().length() <= 0) {
            JOptionPane.showMessageDialog(null, "Necesita ingresar un valor en ASIGNACIONES");
            asignaciones.requestFocus();
        } else if (examenFinal.getText().trim().length() <= 0) {
            JOptionPane.showMessageDialog(null, "Necesita ingresar un valor en EXAMEN FINAL");
            examenFinal.requestFocus();
        } else if (nombre.getText().trim().length() <= 0) {
            JOptionPane.showMessageDialog(null, "Necesita ingresar su NOMBRE COMPLETO   ");
            nombre.requestFocus();
        } else if (matricula.getText().trim().length() <= 0) {
            JOptionPane.showMessageDialog(null, "Necesita ingresar su MATRICULA");
            matricula.requestFocus();
        } else if (carrera.getText().trim().length() <= 0) {
            JOptionPane.showMessageDialog(null, "Necesita ingresar su CARRERA");
            carrera.requestFocus();
        }

    }

    private void practicasKeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_practicasKeyTyped
        //valida y permite solo numeros
        char numeros = evt.getKeyChar();
        if ((numeros < '0' || numeros > '9') && (numeros < ',' || numeros > '.')) {
            JOptionPane.showMessageDialog(null, "Ingresar solo numeros");
            evt.consume();
        }

        //almacena los caracteres ingresado para poder evaluar despues el rango de numero necesario
        String carateresNum = practicas.getText() + numeros;

        //convierte a entero y evalua el rango
        if (Double.parseDouble(carateresNum) < 0 || Double.parseDouble(carateresNum) > 40) {

            JOptionPane.showMessageDialog(null, "Debe de ingresar un valor entre 0 y 40");
            evt.consume();

        }

    }//GEN-LAST:event_practicasKeyTyped

