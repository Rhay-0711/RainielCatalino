    //se encarga de la suma
    private void sumaTotal() {

        //objeto estudiante
        Estudiante estudiante = new Estudiante();
       
        //almacena la suma total de todos los valores
        double resultado = estudiante.sumaTotal(Double.parseDouble(practicas.getText()), Double.parseDouble(parciales.getText()),
                Double.parseDouble(asignaciones.getText()), Double.parseDouble(examenFinal.getText()));

        //evalua si el estudiante aprobo o reprobo
        if (resultado >= 60) {
            notaFinal.setText(nombre.getText() + " : " + "\nResultado de nota final: " + resultado + "\n APROBADO");
        } else {
            notaFinal.setText(nombre.getText() + " : " + "\nResultado de nota final: " + resultado + "\nREPROBADO");
        }

    }

