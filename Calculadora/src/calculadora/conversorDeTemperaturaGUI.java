    //convierte a celcius
    private void celcius() {

        //instancia el objeto
        ConversorTemperatura celcicus = new ConversorTemperatura();

        //guarda el resultado de la conversion a celcius
        double total = celcicus.celius(Double.parseDouble(valores.getText()));

        //muestra el resultado en el text area con el simbolo de grados celcius
        resultado1.setText(total + "°C");

    }

    //convierte a fahrenheit
    private void fahrenheit() {

        //instancia el objeto
        ConversorTemperatura fahrenheit = new ConversorTemperatura();

        //guarda el resultado de la conversion a fahrenheit
        double total = fahrenheit.fahrenheit(Double.parseDouble(valores.getText()));

        //muestra el resultado en el text area con el simbolo de grados fahrenheit
        resultado1.setText(total + "°F");

    }

    //valida si el campo tiene informacion
    private void validarCampo() {

        //evalua si el en el  campo hay texto o mejor dicho un numero
        if (valores.getText().trim().length() <= 0) {
            JOptionPane.showMessageDialog(null, "Necesita ingresar un valor para realizar la OPERACION");
            valores.requestFocus();
        }
    }

    //limpia el campo 
    private void limpiarCampos() {

        valores.setText("");
        valores.requestFocus();

        resultado1.setText("");
        resultado1.requestFocus();

    }

