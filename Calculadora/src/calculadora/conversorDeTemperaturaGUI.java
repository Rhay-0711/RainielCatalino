    //campo donde van los valores
    private void valoresKeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_valoresKeyTyped

        //evalua que solo se ingresen numeros
        char numeros = evt.getKeyChar();
        if ((numeros < '0' || numeros > '9') && (numeros < ',' || numeros > '.')) {
            JOptionPane.showMessageDialog(null, "Ingresar solo numeros");
            evt.consume();
        }
    }//GEN-LAST:event_valoresKeyTyped

