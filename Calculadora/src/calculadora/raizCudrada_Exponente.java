public class raizCudrada_Exponente {
    
    //encuentra la raiz cuadrada de un numero
    public double raizCuadrada(double a){
        
        return Math.sqrt(a);
        
    }
    
    //eleva a un exponente
    public double exponencial(double a, double b){
        
        return Math.pow(a, b);
        
    }
    
}
