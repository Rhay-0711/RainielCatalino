    //realiza la suma
    private void sumar() {

        //instancia el objeto
        calculosAritmeticos suma = new calculosAritmeticos();

        //guarda el resultado de la suma
        double total = suma.sumar(Double.parseDouble(primerValor.getText()), Double.parseDouble(segundoValor.getText()));

        //muestra el resultado en el text area
        resultado.setText(total + "");
    }

