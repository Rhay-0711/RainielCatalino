//Realizar un programa que imprima los números pares del 2 al 100 utilizando ciclos while.

package pares1al100;

/**
 *
 * @author User
 */
public class Pares1Al100 {

    public static void main(String[] args) {
        
        int num = 2;
        
        while (num <= 100) {            
            
            System.out.println(num);
            num += 2;
            
        }
        
    }
    
}
